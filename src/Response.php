declare(strict_types=1);

namespace PapiAI\Core;

/**
 * Immutable value object representing an LLM response.
 *
 * Contains the generated text, any tool calls requested by the model,
 * structured data (when an output schema was used), and token usage statistics.
 */
final class Response
{
    /**
     * Token usage for the request.
     *
     * Typed as the neutral Usage value object; it is still array-accessible
     * (`$response->usage['input_tokens']`) for backward compatibility.
     */
    public readonly Usage $usage;

    public readonly Usage $lastCallUsage;

    /**
     * @param string          $text       The text response from the LLM
     * @param array|null      $data       Parsed structured data (if output schema was used)
     * @param array<ToolCall> $toolCalls  Tool calls made by the LLM
     * @param array<Message>  $messages   Full conversation history
     * @param Usage|array     $usage      Token usage (a raw provider array is accepted and normalised)
     * @param string|null     $stopReason     Why the response ended, in the provider's own words
     * @param StopReason      $stoppedBecause Why the response ended, in the same words for every provider
     * @param array<string, array> $replay What the provider needs back verbatim on the next request, keyed by
     *   provider name. It travels on the assistant message built by toMessage().
     * @param Usage|null      $lastCallUsage The tokens of the final provider call, when $usage covers a whole
     *   agent run. Its input tokens say how full the context is. Defaults to $usage.
     */
    public function __construct(
        public readonly string $text,
        public readonly ?array $data = null,
        public readonly array $toolCalls = [],
        public readonly array $messages = [],
        Usage|array $usage = [],
        public readonly ?string $stopReason = null,
        public readonly StopReason $stoppedBecause = StopReason::Other,
        public readonly array $replay = [],
        ?Usage $lastCallUsage = null,
    ) {
        $this->usage = is_array($usage) ? Usage::fromArray($usage) : $usage;
        $this->lastCallUsage = $lastCallUsage ?? $this->usage;
    }

    /**
     * Check if the response has tool calls.
     *
     * @return bool True if the model requested one or more tool invocations
     */
    public function hasToolCalls(): bool
    {
        return !empty($this->toolCalls);
    }

    /**
     * The assistant message that continues the conversation, carrying what the provider needs back.
     */
    public function toMessage(): Message
    {
        return Message::assistant($this->text, $this->toolCalls ?: null, $this->replay);
    }

    /**
     * Whether the output ceiling cut the answer short.
     */
    public function isTruncated(): bool
    {
        return $this->stoppedBecause === StopReason::MaxTokens;
    }

    /**
     * Check if the response has structured data.
     *
     * @return bool True if the response was parsed into structured data via an output schema
     */
    public function hasData(): bool
    {
        return $this->data !== null;
    }

    /**
     * Get the number of input tokens consumed by this request.
     *
     * @return int Input token count, or 0 if usage data is unavailable
     */
    public function getInputTokens(): int
    {
        return $this->usage->inputTokens;
    }

    /**
     * Get the number of output tokens generated by this response.
     *
     * @return int Output token count, or 0 if usage data is unavailable
     */
    public function getOutputTokens(): int
    {
        return $this->usage->outputTokens;
    }

    /**
     * Get total token count (input + output).
     *
     * @return int Combined token count for cost estimation
     */
    public function getTotalTokens(): int
    {
        return $this->usage->totalTokens;
    }

    /**
     * Create from an Anthropic API response payload.
     *
     * @deprecated Response mapping now lives in each provider package (see AnthropicProvider); build a
     *   Response with the neutral constructor instead. Kept for backward compatibility.
     *
     * @param array $response Raw Anthropic API response
     * @param array<Message> $messages Conversation history to attach
     *
     * @return self Parsed response with text, tool calls, and usage
     */
    public static function fromAnthropic(array $response, array $messages = []): self
    {
        $text = '';
        $toolCalls = [];

        foreach ($response['content'] ?? [] as $block) {
            if ($block['type'] === 'text') {
                $text .= $block['text'];
            } elseif ($block['type'] === 'tool_use') {
                $toolCalls[] = ToolCall::fromAnthropic($block);
            }
        }

        return new self(
            text: $text,
            toolCalls: $toolCalls,
            messages: $messages,
            usage: $response['usage'] ?? [],
            stopReason: $response['stop_reason'] ?? null,
            stoppedBecause: match ($response['stop_reason'] ?? null) {
                'end_turn', 'stop_sequence' => StopReason::Stop,
                'max_tokens', 'model_context_window_exceeded' => StopReason::MaxTokens,
                'tool_use' => StopReason::ToolCalls,
                'refusal' => StopReason::Refused,
                default => StopReason::Other,
            },
        );
    }

    /**
     * Create from an OpenAI API response payload.
     *
     * @param array $response Raw OpenAI API response
     * @param array<Message> $messages Conversation history to attach
     *
     * @return self Parsed response with text, tool calls, and usage
     */
    public static function fromOpenAI(array $response, array $messages = []): self
    {
        $choice = $response['choices'][0] ?? [];
        $message = $choice['message'] ?? [];

        $toolCalls = [];
        foreach ($message['tool_calls'] ?? [] as $tc) {
            $toolCalls[] = ToolCall::fromOpenAI($tc);
        }

        return new self(
            text: $message['content'] ?? '',
            toolCalls: $toolCalls,
            messages: $messages,
            usage: $response['usage'] ?? [],
            stopReason: $choice['finish_reason'] ?? null,
            stoppedBecause: $toolCalls !== [] ? StopReason::ToolCalls : match ($choice['finish_reason'] ?? null) {
                'stop' => StopReason::Stop,
                'length', 'model_length' => StopReason::MaxTokens,
                'tool_calls', 'function_call' => StopReason::ToolCalls,
                'content_filter' => StopReason::Refused,
                default => StopReason::Other,
            },
        );
    }

    /**
     * Return a new Response with structured data attached.
     *
     * @param array $data The parsed structured data to include
     *
     * @return self A new immutable Response instance with the data set
     */
    public function withData(array $data): self
    {
        return $this->with(['data' => $data]);
    }

    /**
     * Return a new Response carrying a different conversation history.
     *
     * @param array<Message> $messages
     */
    public function withMessages(array $messages): self
    {
        return $this->with(['messages' => $messages]);
    }

    /**
     * A copy reporting the tokens of a whole run, with this response's own usage kept as the last call's.
     *
     * @param Usage $run The sum over every provider call in the run, this one included
     */
    public function withRunUsage(Usage $run): self
    {
        return $this->with(['usage' => $run, 'lastCallUsage' => $this->lastCallUsage]);
    }

    /**
     * @param array<string, mixed> $changes Constructor arguments to replace, by name
     */
    private function with(array $changes): self
    {
        return new self(...$changes + [
            'text' => $this->text,
            'data' => $this->data,
            'toolCalls' => $this->toolCalls,
            'messages' => $this->messages,
            'usage' => $this->usage,
            'stopReason' => $this->stopReason,
            'stoppedBecause' => $this->stoppedBecause,
            'replay' => $this->replay,
            'lastCallUsage' => $this->lastCallUsage,
        ]);
    }
}
